export type ServiceName = keyof typeof SERVICE_CATALOG;
export const SERVICE_NAMES = Object.keys(SERVICE_CATALOG) as ServiceName[];
export const CATEGORIES = SERVICE_CATALOG;
export type CategoryName = string;
export const CATEGORY_NAMES = SERVICE_NAMES;

function normaliseService(value: string): ServiceName | null {
  if (value.toLowerCase() === 'plant hire') return 'Plant Hire';
  if (SERVICE_NAMES.includes(value as ServiceName)) return value as ServiceName;
  return null;
}

export function isValidService(value: string): value is ServiceName {
  return SERVICE_NAMES.includes(value as ServiceName) || value.toLowerCase() === 'plant hire';
}

export function categoriesForService(service: string): string[] {
  const normalised = normaliseService(service);
  return normalised ? Object.keys(SERVICE_CATALOG[normalised]) : [];
}

export function itemsForCategory(service: string, category: string): string[] {
  const normalised = normaliseService(service);
  if (!normalised) return [];
  const catalogue = SERVICE_CATALOG[normalised] as Record<string, readonly string[]>;
  return catalogue[category] ? [...catalogue[category]] : [];
}

export function isValidCategory(value: string): boolean {
  return SERVICE_NAMES.some((service) => categoriesForService(service).includes(value));
}

export function isValidSubcategory(service: string, category: string, item?: string): boolean {
  if (item === undefined) {
    const normalised = normaliseService(service);
    if (!normalised) return false;
    const legacyLabels: Record<ServiceName, string[]> = {
      Materials: ['Bricks and blocks', 'Aggregates', 'Timber', 'Insulation', 'Roofing materials', 'Plumbing and drainage materials', 'Electrical supplies', 'Other materials'],
      Waste: ['Skip hire', 'Muck away', 'Waste collection', 'Recycling and disposal', 'Other waste services'],
      'Plant Hire': ['Excavators', 'Dumpers', 'Access and scaffolding', 'Welfare units', 'Generators and power', 'Other plant hire'],
      'Contractor Services': [],
      'Professional Services': [],
    };
    return categoriesForService(normalised).includes(category) || legacyLabels[normalised].includes(category) || Object.values(SERVICE_CATALOG[normalised]).some((items) => items.includes(category));
  }
  return itemsForCategory(service, category).includes(item);
}

